use super::*;

fn m(surface: &str, features: &str) -> Morpheme {
    let f: Vec<&str> = features.split(',').collect();
    Morpheme::from_features(surface, &f)
}

/// The merge rules on IPADIC morphemes, without a dictionary: Word for Mac's words for
/// 日本語の文章を書いています。 and 東京都千代田区の会議室で打ち合わせを行う予定です。.
#[test]
fn morphemes_merge_into_word_for_macs_words() {
    let s = [
        m("日本語", "名詞,一般,*,*,*,*,日本語"),
        m("の", "助詞,連体化,*,*,*,*,の"),
        m("文章", "名詞,一般,*,*,*,*,文章"),
        m("を", "助詞,格助詞,一般,*,*,*,を"),
        m("書い", "動詞,自立,*,*,五段・カ行イ音便,連用タ接続,書く"),
        m("て", "助詞,接続助詞,*,*,*,*,て"),
        m("い", "動詞,非自立,*,*,一段,連用形,いる"),
        m("ます", "助動詞,*,*,*,特殊・マス,基本形,ます"),
        m("。", "記号,句点,*,*,*,*,。"),
    ];
    assert_eq!(merge(&s), ["日本語", "の", "文章", "を", "書いて", "います", "。"]);
    let s = [
        m("東京", "名詞,固有名詞,地域,一般,*,*,東京"),
        m("都", "名詞,接尾,地域,*,*,*,都"),
        m("十", "名詞,数,*,*,*,*,十"),
        m("五", "名詞,数,*,*,*,*,五"),
        m("分", "名詞,接尾,助数詞,*,*,*,分"),
        m("ご", "接頭詞,名詞接続,*,*,*,*,ご"),
        m("意見", "名詞,一般,*,*,*,*,意見"),
        m("降る", "動詞,自立,*,*,五段・ラ行,基本形,降る"),
        m("らしい", "助動詞,*,*,*,形容詞・イ段,基本形,らしい"),
        m("株式会社", "名詞,一般,*,*,*,*,株式会社"),
        m("すでに", "副詞,一般,*,*,*,*,すでに"),
        m("子ども", "名詞,一般,*,*,*,*,子ども"),
        m("たち", "名詞,接尾,一般,*,*,*,たち"),
        m("甘", "形容詞,自立,*,*,形容詞・アウオ段,ガル接続,甘い"),
        m("すぎ", "動詞,非自立,*,*,一段,連用形,すぎる"),
        m("て", "助詞,接続助詞,*,*,*,*,て"),
    ];
    assert_eq!(merge(&s), ["東京都", "十五分", "ご意見", "降る", "らしい", "株式", "会社", "すで", "に", "子ども", "たち", "甘すぎて"]);
    assert!(merge(&[]).is_empty());
    // Features may be missing (an unknown word): read as `*`.
    assert_eq!(Morpheme::from_features("x", &[]).pos, "*");
}

/// Word for Mac's words for our own sentences (its `words` collection with Japanese editing,
/// 2026-10-20), where a dictionary is installed (`WORDCRAFT_JA_DICT` or the places
/// [`find_dictionary`] looks in): the analysis matches Word on at least 85 % of the sentences.
#[test]
fn sentences_break_into_word_for_macs_words_with_a_dictionary() {
    if find_dictionary().is_none() {
        eprintln!("no Japanese dictionary: skipped");
        return;
    }
    let mut same = 0;
    for row in WORD_FOR_MAC {
        let want: Vec<&str> = row.split('|').collect();
        let text: String = want.concat();
        let ends = word_ends(&text).expect("words");
        let mut got = Vec::new();
        let mut at = 0;
        for e in ends {
            got.push(&text[at..e]);
            at = e;
        }
        if got == want {
            same += 1;
        } else {
            eprintln!("Word: {}\n ours: {}", want.join("|"), got.join("|"));
        }
    }
    assert!(same * 100 >= WORD_FOR_MAC.len() * 85, "{same} of {}", WORD_FOR_MAC.len());
}

#[test]
fn hostile_text_is_safe() {
    for t in ["", " ", "\u{0}", "a b", "  空白  の  ある  文", &"あ".repeat(70_000)] {
        if let Some(ends) = word_ends(t) {
            assert!(ends.windows(2).all(|w| w[0] <= w[1]) && ends.last().copied().unwrap_or(0) <= t.len(), "{t:?} {ends:?}");
            assert!(ends.iter().all(|e| t.is_char_boundary(*e)));
        }
    }
}

